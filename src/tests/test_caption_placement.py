"""Captions stay in the frame, move as dragged, keep to their clip, and never double up."""
import shutil
import subprocess
from fractions import Fraction
from types import SimpleNamespace

import pytest

import edit_render
import media_probe
import render_engine

PRESETS = [name for name, style in render_engine.SUBTITLE_PRESETS.items() if style]
LONG = "One of these advertisements was generated by artificial intelligence technology yesterday".split()


def transcript(*clips):
    segments = []
    for start, words in clips:
        spoken = [{"word": " " + w, "start": start + i * .25, "end": start + i * .25 + .22} for i, w in enumerate(words)]
        segments.append({"start": spoken[0]["start"], "end": spoken[-1]["end"], "text": " ".join(words), "words": spoken})
    return {"language": "en", "segments": segments}


@pytest.fixture
def frame(monkeypatch):
    def use(width, height):
        monkeypatch.setattr(media_probe, "frame_size", lambda *a, **k: (width, height))
    use(1920, 1080)
    return use


def track(said=None, parts=None, hidden=(), **fields):
    style, preset = edit_render.build_style({"subtitle_preset": "custom", "subtitle_size": 19, **fields})
    return edit_render.caption_track(said or transcript((0.1, LONG)), [(0, 30)], style, preset, "video", None, parts, hidden)


@pytest.mark.parametrize("size", [(1920, 1080), (1080, 1920)])
@pytest.mark.parametrize("preset", ["custom", "animated", *PRESETS])
@pytest.mark.parametrize("x,down", [(0.02, -0.9), (0.98, 0.9), (0.6, 0)])
def test_captions_cannot_leave_the_frame(frame, size, preset, x, down):
    frame(*size)
    boxes = track(subtitle_preset=preset, pos_x=x, offset_y=down, caption_lines=1, words_per_caption=8)["boxes"]
    assert boxes
    for box in boxes:
        assert box["l"] >= 0 and box["t"] >= 0 and box["r"] <= 1 and box["b"] <= 1


@pytest.mark.parametrize("preset", ["animated", "impact_yellow", "custom"])
def test_a_drag_moves_exactly_as_far_as_it_was_dragged(frame, preset):
    short = transcript((0.1, ["Hi", "there"]))
    before = track(short, subtitle_preset=preset, subtitle_size=12)["boxes"][0]
    after = track(short, subtitle_preset=preset, subtitle_size=12, pos_x=0.6, offset_y=-0.2)["boxes"][0]
    assert after["l"] - before["l"] == pytest.approx(0.1, abs=0.002)
    assert after["t"] - before["t"] == pytest.approx(-0.2, abs=0.002)


@pytest.mark.parametrize("preset", ["custom", "animated", "impact_yellow"])
def test_no_caption_spans_two_clips(frame, preset):
    said = transcript((0.1, "is the AI version".split()), (1.2, "Well this one".split()))
    made = track(said, parts=[0.0, 1.15], subtitle_preset=preset, words_per_caption=6)
    cues = [block.split("\n", 2)[2] for block in made["srt"].strip().split("\n\n")]
    assert len(cues) == 2 and "Well" not in cues[0]
    assert all(box["e"] <= 1.16 or box["s"] >= 1.15 for box in made["boxes"])


def test_a_hidden_clip_gets_no_captions_but_stays_in_the_list(frame):
    said = transcript((0.1, ["first"]), (2.2, ["second"]))
    made = track(said, parts=[0.0, 2.0], hidden={0})
    drawn = [line for line in made["ass"].split("\n") if line.startswith("Dialogue:")]
    assert len(drawn) == 1 and "second" in drawn[0]
    assert "first" in made["srt"]


@pytest.mark.parametrize("preset", ["bubble", "white_card", "box"])
def test_a_boxed_template_paints_its_own_colour(preset):
    style = render_engine.SUBTITLE_PRESETS[preset]
    assert style.outline_colour == style.back_colour    # libass paints boxes in the outline colour
    assert style.outline > 0 and style.primary_colour != style.outline_colour


@pytest.mark.skipif(not shutil.which("ffmpeg"), reason="ffmpeg is not installed")
def test_an_export_is_marked_and_recognised(tmp_path, monkeypatch):
    import burned_captions
    monkeypatch.chdir(tmp_path)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "color=s=320x240:d=1", "-c:v", "libx264",
                    "-pix_fmt", "yuv420p", "in.mp4"], check=True)
    (tmp_path / "c.ass").write_text("[Script Info]\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour\n"
                                    "Style: D,Arial,20,&H00FFFFFF\n[Events]\nFormat: Layer, Start, End, Style, Text\n"
                                    "Dialogue: 0,0:00:00.00,0:00:01.00,D,hello\n")
    render_engine.burn_subtitles("in.mp4", "out.mp4", ass_path="c.ass", job_prefix="mark")
    assert burned_captions.detect("out.mp4", {}) is True
    assert burned_captions.detect("in.mp4", {}) is False


def test_writing_in_shot_is_not_captions(monkeypatch):
    import burned_captions
    said = transcript((0, "measure twice before cutting anything expensive today".split()))
    monkeypatch.setattr(burned_captions, "marked", lambda path: False)
    monkeypatch.setattr(burned_captions, "_frame", lambda path, at: "picture")
    monkeypatch.setattr(burned_captions, "_read", lambda frame: {"whiteboard", "bottlenecks", "agenda"})
    assert burned_captions.detect("x.mp4", said) is False
    monkeypatch.setattr(burned_captions, "_read", lambda frame: {"measure", "twice", "before", "cutting"})
    assert burned_captions.detect("x.mp4", said) is True


def test_turning_one_of_two_clips_gives_the_first_clips_shape(monkeypatch):
    import project_plan
    from segment_render import Canvas
    wide, tall = Canvas(1920, 1080, Fraction(25)), Canvas(1080, 1920, Fraction(25))
    given = []

    def canvas(sources, current=None):
        given.append(current)
        return tall
    monkeypatch.setattr(project_plan.pipeline, "project_canvas", canvas)
    monkeypatch.setattr(project_plan, "_register_clip", lambda *a, **k: "job")
    monkeypatch.setattr(project_plan, "_submission", lambda *a, **k: None)
    options = project_plan.pipeline.EditOptions(canvas=wide)
    clips = []
    for key, was, now in (("a", 0, 90), ("b", 0, 0)):
        previous = {"cut": SimpleNamespace(canvas=wide), "rotate": was, "options": options,
                    "keep_segments": [(0, 1)], "input_video_path": key, "clip_keys": [key]}
        clips.append(project_plan.Clip(key, key, None, now, {}, "auto", previous=previous, input_path=key + "-new",
                                       job_id=key + "2"))
    project_plan.submit_edit("owner", clips, options, [None, None], 0.5)
    assert given == [None]      # the old landscape shape does not win the tie
